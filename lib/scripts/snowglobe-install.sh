_set_username() {
	[ "${USERNAME-}" ] && unset USERNAME
	printf "Warning: Username will be cleansed of characters that are not [a-z][A-Z][0-9], -, or _\n"
	while :; do
		printf "Username: "
		read -r USERNAME
		USERNAME="$(printf "%s" "$USERNAME" | tr -dc '[:digit:][:upper:][:lower:]-_')"
		if [ ! "${USERNAME-}" ]; then
			printf "Username cannot be empty.\n"
			continue
		else
			if [ "${USERS-}" ]; then
				for user in $USERS; do
					if [ "$user" = "$USERNAME" ]; then
						printf "\nWarning: A user with that username has already been configured. Enter another username.\n"
						continue
					fi
				done
			fi
			break
		fi
	done
	if [ "${USERNAME}" = "root" ]; then
		IS_ROOT=1
	else
		[ "${IS_ROOT}" ] && unset IS_ROOT
	fi

}

