		printf "\n"
		if [ ! "${PASSWORD-}" ]; then
			y_or_n "No password provided. Try Again?" default="yes" && continue
			break
		fi
		PASSWORD2="$(_enter_secret "Confirm Password: ")"
		printf "\n"
		if [ "${PASSWORD}" != "${PASSWORD2-}" ]; then
			printf "\nPassword do not match! Try again.\n"
			continue
		else
			break
		fi
	done
	unset PASSWORD2
}

_add_ssh_key() {
	[ "${1-}" ] || _errormsg "_add_ssh_key called without any arguments."
	if [ ! "${AUTHORIZED_SSH_KEYS-}" ]; then
		AUTHORIZED_SSH_KEYS="$1"
	else
		AUTHORIZED_SSH_KEYS="$AUTHORIZED_SSH_KEYS ""$1"
	fi
}

_configure_ssh_keys() {
	[ "${AUTHORIZED_SSH_KEYS-}" ] && unset AUTHORIZED_SSH_KEYS
	if [ "${HAS_KEYRING-}" ]; then
		SSH_KEY_PAIRS="$(nix eval --file "$KEYRING_FILE" keyring.ssh | tr -d '{  }')"
	fi
	if [ "${SSH_KEY_PAIRS-}" ]; then
		_build_key_dictionary "$SSH_KEY_PAIRS"
		if y_or_n "Found configured ssh keys on your keyring. Would you like to use one of those?"; then
			SSH_KEY_NAMES="$(ls -A "$KEY_DICTIONARY_DIR")"
			while :; do
				SSH_KEY_NAME="$(
					for key in $SSH_KEY_NAMES; do
						printf "%s\n" "$key"
					done | fzf \
						--border \
						--border-label-pos 1:bottom \
						--border-label="Found the following SSH keys on your keyring. Use one of these? (Ctrl+C or esc to cancel)"
				)"
				if [ ! "${SSH_KEY_NAME}" ]; then
					y_or_n "No key was selected. Try again?" default="yes" || break
				else
					_add_ssh_key "$SSH_KEY_NAME"
					for keyname in $SSH_KEY_NAMES; do
						if [ "$keyname" != "$SSH_KEY_NAME" ]; then
							if [ ! "${TMP-}" ]; then
								TMP="$keyname"
							else
								TMP="$TMP ""$keyname"
							fi
						fi
					done
					SSH_KEY_NAMES="$TMP"
					unset TMP

					if [ ! "${SSH_KEY_NAMES-}" ]; then
						break
					else
						y_or_n "Add another key from your keyring?" || break
					fi
				fi
			done
		fi
	fi

	if [ "${AUTHORIZED_SSH_KEYS}" ]; then
		y_or_n "Add any additional keys not present on your keyring?" default="no" || return 0
	fi

	[ ! "${KEY_DICTIONARY_DIR}" ] && _build_key_dictionary
	while :; do
		while :; do
			printf "Enter a valid ssh public key: "
			read -r SSH_PUBLIC_KEY
			if [ ! "${SSH_PUBLIC_KEY-}" ]; then
				y_or_n "No key was entered. Try again" || return 1
			else
				printf "%s\n" "$SSH_PUBLIC_KEY" >/tmp/verify-ssh || _errormsg "Failed to write key value /tmp/verify-ssh"
				if ! ssh-keygen -l -f /tmp/verify-ssh >/dev/null 2>&1; then
					y_or_n "That ssh does not seem valid. Try again?" || return 1
				else
					break
				fi
			fi
		done

		KEY_NAMES="$(ls -A "$KEY_DICTIONARY_DIR")"
		while :; do
			printf "Warning: key name will be stripped of numbers and special characters except for '-' and '_'\n"
			printf "Give a name to this key for your keyring: "
			read -r SSH_KEY_NAME
			SSH_KEY_NAME="$(printf "%s" "$SSH_KEY_NAME" | tr -dc '[:upper:][:lower:]-_')"
			if [ ! "${SSH_KEY_NAME-}" ]; then
				printf "Key name cannot be empty. Try again.\n"
				continue
			else
				if [ "${KEY_NAMES-}" ]; then
					for keyname in $KEY_NAMES; do
						if [ "${SSH_KEY_NAME}" = "$keyname" ]; then
							DUPLICATE_DETECTED=1
							break
						fi
					done
					if [ "${DUPLICATE_DETECTED-}" ]; then
						unset DUPLICATE_DETECTED
						printf "A key with the provided name is already present on your keyring. Try again.\n"
						continue
					fi
				fi
			fi
			printf "Key name: %s\n" "$SSH_KEY_NAME"
			break
		done

		_add_ssh_key "$SSH_KEY_NAME"
		sed -i "s|\(ssh = {\)\([^}]*\)|\1\n\t$SSH_KEY_NAME = \"$SSH_PUBLIC_KEY\";|" "$KEYRING_FILE"
		printf "%s\n" "$SSH_PUBLIC_KEY" >"$KEY_DICTIONARY_DIR/$SSH_KEY_NAME"
		y_or_n "Authorize another ssh key?" || break
	done

	_remove_key_dictionary
}

_select_browser() {
	FIREFOX_DESCRIPTION="Default firefox configuration from mozilla."
	LIBREWOLF_DESCRIPTION="debloated Mozilla Firefox configuration with an emphasis on
privacy and security."
	CHROMIUM_DESCRIPTION="open source alternative to google-chrome."
	HELIUM_DESCRIPTION="Debloated chromium based browser designed with 
simplicity and security in mind."
	TOR_BROWSER_DESCRIPTION="Firefox based browser officially supported by the tor project
for use of The Onion Router protocol (TOR)"

	IFS='|'
	while :; do
		SELECTED="$(
			for browser in $SUPPORTED_WEB_BROWSERS; do
				printf "%s\n" "$browser"
			done | fzf \
				--disabled \
				--border \
				--border-label-pos 1:bottom \
				--border-label="Pick your favorite web browser" \
				--preview="
					case {} in
					'Firefox') printf '$FIREFOX_DESCRIPTION'
					'Librewolf') printf '$LIBREWOLF_DESCRIPTION'
					'Chromium') printf '$CHROMIUM_DESCRIPTION'
					'Helium') printf '$HELIUM_DESCRIPTION'
					'Tor-Browser') printf '$TOR_BROWSER_DESCRIPTION'
					esac
				" | tr '[:upper:]' '[:lower:]'
		)"

		if [ ! "${SELECTED-}" ]; then
			y_or_n "No browser selected. Try again?" default="yes" || break
		else
			case "$SELECTED" in
			"chromium") WEB_BROWSER="chromium-browser" ;;
			*) WEB_BROWSER="$SELECTED" ;;
			esac
			break
		fi
	done

	unset IFS SELECTED FIREFOX_DESCRIPTION LIBREWOLF_DESCRIPTION CHROMIUM_DESCRIPTION HELIUM_DESCRIPTION TOR_BROWSER_DESCRIPTION
}

_set_permission() {
	[ "${1-}" ] || _errormsg "_set_permission called without any arguments."
	if [ ! "${USER_PERMISSIONS-}" ]; then
		USER_PERMISSIONS="$1"
	else
		USER_PERMISSIONS="$USER_PERMISSIONS ""$1"
	fi
}

_set_permissions() {
	[ "${USER_PERMISSIONS-}" ] && unset USER_PERMISSIONS
	y_or_n "Should this user have access to privilege escalation? (ability to run as sudo)" default="yes" && _set_permission "wheel"
	if [ "${DESKTOP_ENVIRONMENT-}" ]; then
		y_or_n "Should this user be allowed to add, remove, and manage network connections with networkmanager?" default="yes" && _set_permission "networkmanager"
	fi
}

_add_user() {
	if [ ! "${USERS-}" ]; then
		USERS="$1"
	else
		USERS="$USERS ""$1"
	fi
}

# user creation loop
while :; do
	_set_username
	y_or_n "Set a password for this user?" default="yes" && _set_password
	y_or_n "Add an ssh key for authentication with this user over openssh?" default="no" && _configure_ssh_keys
	# set permissions for normal users
	if [ ! "${IS_ROOT-}" ]; then
		_set_permissions
		if [ ! "${PASSWORD-}" ]; then
			for permission in ${USER_PERMISSIONS}; do
				if [ "${permission}" = "wheel" ]; then
					printf "\nWARNING:\nWheel permission is set, but this user has no password.\n"
					printf "You will not be able to run commands with 'sudo' without a password.\n"
					y_or_n "Set a password for this user?" default="yes" && _set_password
					break
				fi
			done
		fi

		if [ "${DESKTOP_ENVIRONMENT-}" ]; then
			y_or_n "Install a web browser?" default="yes" && _select_browser
		fi
	fi

	while :; do
		while :; do
			if [ ! "${PASSWORD-}" ] && [ ! "${AUTHORIZED_SSH_KEYS}" ]; then
				printf "\nWARNING: Neither a password nor an authorized SSH key was set for this user.\n"
				printf "At least one must be set, or the user will be inaccessible after installation completes.\n"
				printf "1. Password\n"
				printf "2. SSH key\n"
				printf "Enter the number corresponding to which you want to set: "
				read -r SELECTED
				SELECTED="$(printf "%s" "$SELECTED" | tr -dc '[:digit:]')"
				if [ ! "${SELECTED}" ] || [ "${SELECTED}" -gt 2 ]; then
					printf "Invalid selection. Try again\n"
					continue
				fi
				case "$SELECTED" in
				"1") _set_password ;;
				"2") _configure_ssh_keys ;;
				esac
			else
				break
			fi
		done
		printf "\nConfiguration for user:\n"
		printf "Username - %s\n" "$USERNAME"
		[ "${PASSWORD-}" ] && printf "Password - =*Redacted*=\n"
		[ "${WEB_BROWSER-}" ] && printf "Preferred Web Browser = %s\n" "$WEB_BROWSER"
		if [ "${AUTHORIZED_SSH_KEYS}" ]; then
			for key in $AUTHORIZED_SSH_KEYS; do
				printf "Authorized SSH key - %s\n" "$key"
			done
		fi
		if [ "${IS_ROOT-}" ]; then
			printf "Permission - System Administrator\n\n"
		elif [ "${USER_PERMISSIONS-}" ]; then
			for permission in $USER_PERMISSIONS; do
				printf "Permission - %s\n" "$permission"
			done
		else
			printf "Permission - None\n\n"
		fi

		printf "\n"
		y_or_n "Are you satisfied with the current configuration?" default="yes" && break
		clear
		OPTIONS="Username|Password|Permissions|Authorized Keys"
		[ "${WEB_BROWSER-}" ] && OPTIONS="$OPTIONS""|Web Browser"
		IFS='|'
		SELECTED="$(
			for option in $OPTIONS; do
				printf "%s\n" "$option"
			done | fzf \
				--disabled \
				--border \
				--border-label-pos 1:bottom \
				--border-label="Which do you wish to change? (Press esc or Ctrl+C to continue)"
		)"
		unset IFS
		case "${SELECTED-}" in
		"Username") _set_username ;;
		"Password") _set_password ;;
		"Web Browser") _select_browser ;;
		"Authorized Keys") _configure_ssh_keys ;;
		"Permissions") _set_permissions ;;
		*) continue ;;
		esac
	done

	USER_CONFIG_DIR="$HOST_CONFIG_DIR/users/$USERNAME"
	USER_CONFIG_FILE="$USER_CONFIG_DIR/default.nix"
	mkdir -p "$USER_CONFIG_DIR" || _errormsg "Failed to create $USER_CONFIG_DIR"

	printf "{ config, ... }:\n{" >"$USER_CONFIG_FILE"
	[ "${PASSWORD-}" ] && printf "sops.secrets.%s_password.neededForUsers = true;\n" "$USERNAME" >>"$USER_CONFIG_FILE"
	printf "users.users.%s = {\n" "$USERNAME" >>"$USER_CONFIG_FILE"
	[ "${PASSWORD-}" ] && printf "hashedPasswordFile = config.sops.secrets.%s_password.path;\n" "$USERNAME" >>"$USER_CONFIG_FILE"
	[ ! "${IS_ROOT-}" ] && printf "isNormalUser = true;\n" >>"$USER_CONFIG_FILE"
	if [ "${AUTHORIZED_SSH_KEYS-}" ]; then
		printf "openssh.authorizedKeys.keys = with config.keyring.ssh; [\n" >>"$USER_CONFIG_FILE"
		for key in $AUTHORIZED_SSH_KEYS; do
			printf "%s\n" "$key" >>"$USER_CONFIG_FILE"
		done
		printf "];\n" >>"$USER_CONFIG_FILE"
	fi

	if [ "${USER_PERMISSIONS-}" ]; then
		printf "extraGroups = [ " >>"$USER_CONFIG_FILE"
		for permission in $USER_PERMISSIONS; do
			case "$permission" in
			"wheel") printf "\"wheel\"\n" >>"$USER_CONFIG_FILE" ;;
			"networkmanager") printf "\"networkmanager\"\n" >>"$USER_CONFIG_FILE" ;;
			esac
		done
		printf "];\n" >>"$USER_CONFIG_FILE"
	fi

	printf "};\n}" >>"$USER_CONFIG_FILE"

	if [ "${WEB_BROWSER-}" ]; then
		sed -i '$ s/.$//' "$HOST_CONFIG_FILE"
		_debugmsg "Installing browser: $WEB_BROWSER"
		if grep -q "programs.$WEB_BROWSER" "$HOST_CONFIG_FILE"; then
			sed -i "s|\(installForUsers = [\)\([^\]]*\)|\1\n\t\"$USERNAME\"|" "$HOST_CONFIG_FILE"
		else
			printf "
				programs.%s = {
					enable = true;
					installGlobally = lib.mkDefault false;
					installForUsers = [
						\"%s\"
					];
				};
			}" "$WEB_BROWSER" "$USERNAME" >>"$HOST_CONFIG_FILE"
		fi
	fi

	_add_user "$USERNAME"

	printf "\nConfigured Users:\n"
	for user in $USERS; do
		printf "%s\n" "$user"
	done
	printf "\n"
	[ "${PASSWORD-}" ] && printf "%s_password: %s\n" "$USERNAME" "$(mkpasswd -s "$PASSWORD")" >>"$HOST_SECRETS_FILE"

	unset USERNAME PASSWORD WEB_BROWSER AUTHORIZED_SSH_KEYS USER_PERMISSIONS
	y_or_n "Add/Configure another user?" default="no" || break
done

# use the auto generated keys in the installer for the host ssh identity
cat /etc/ssh/ssh_host_ed25519_key.pub | sed "s|root@nixos-installer|root@$HOSTNAME|" >"$HOST_CONFIG_DIR/ssh_host_ed25519_key.pub"
cat /etc/ssh/ssh_host_rsa_key.pub | sed "s|root@nixos-installer|root@$HOSTNAME|" >"$HOST_CONFIG_DIR/ssh_host_rsa_key.pub"
sed -i '$ s/.$//' "$HOST_CONFIG_FILE"

printf "\nenvironment = {
    etc = {
      \"ssh/ssh_host_ed25519_key.pub\".source = ./ssh_host_ed25519_key.pub;
      \"ssh/ssh_host_rsa_key.pub\".source = ./ssh_host_rsa_key.pub;
    };
};

sops.secrets = {
	ssh_host_ed25519_key.path = \"/etc/ssh/ssh_host_ed25519_key\";
	ssh_host_rsa_key.path = \"/etc/ssh/ssh_host_rsa_key\";
};\n}" >>"$HOST_CONFIG_FILE"

_format_secret() {
	cat "$1" | while read -r line; do
		printf "  %s\n" "$line" >>"$HOST_SECRETS_FILE"
	done
}

printf "\nssh_host_ed25519_key: |\n" >>"$HOST_SECRETS_FILE"
_format_secret /etc/ssh/ssh_host_ed25519_key
printf "\nssh_host_rsa_key: |\n" >>"$HOST_SECRETS_FILE"
_format_secret /etc/ssh/ssh_host_rsa_key

# encrypt secrets file
if [ -e "$HOST_SECRETS_FILE" ]; then
	sops --config "$CONFIG_ROOT/.sops.yaml" -e -i "$HOST_SECRETS_FILE" || _errormsg "Failed to encrypt the secrets file for this host."
fi

find "$CONFIG_ROOT" -type f -not -path '*/.*' | while read -r file; do
	case "$file" in
	*".nix") nixfmt "$file" || printf "Warning: Failed to format nix file %s" "$file" ;;
	*) continue ;;
	esac
done

